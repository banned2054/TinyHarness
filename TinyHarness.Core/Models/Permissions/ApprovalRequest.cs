using TinyHarness.Core.Models.Tools;

namespace TinyHarness.Core.Models.Permissions;

/// <summary>
///     <para>
///         交给审批人的完整请求：冻结计划、执行分类、允许的授权范围、审核员备注与 AI 审核结果。
///         除冻结计划与分类外，其余字段仅供展示，不能授予任何权限。
///     </para>
///     <para>
///         The complete request handed to an approver: the frozen plan, execution level, allowed grant scopes,
///         reviewer note and AI-review result. Except for the frozen plan and level, all fields are display-only
///         and never grant authority.
///     </para>
/// </summary>
/// <remarks>
///     <para>
///         <see cref="DisplayNotes" /> 由宿主按 <see cref="Services.Permissions.ApprovalDisplay" />
///         统一生成（后端与隔离声明、文件与网络权限、有效期、活动授权摘要），CLI 与 Desktop 一致。
///     </para>
///     <para>
///         <see cref="DisplayNotes" /> is generated by the host through
///         <see cref="Services.Permissions.ApprovalDisplay" /> (backend and isolation declarations, file and
///         network permissions, validity, active grant summaries), identical for CLI and Desktop.
///     </para>
/// </remarks>
public sealed record ApprovalRequest(
    ToolPreparation          Preparation,
    PermissionLevel          Level,
    IReadOnlyList<GrantScope> AllowedScopes,
    string?                  ReviewerNote,
    AiReviewResult?          Review,
    IReadOnlyList<string>?   DisplayNotes = null);
